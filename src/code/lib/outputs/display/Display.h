class Display {
  public:
    // Constants for standard 4-pin OLED sizing
    static const int SCREEN_WIDTH = 128;
    static const int SCREEN_HEIGHT = 64;
    static const uint8_t OLED_RESET = -1; // Share microcontroller reset pin
    static const uint8_t I2C_ADDRESS = 0x3C; // Standard SSD1306 address

    // Constructor maps internally to the Adafruit driver instantiation
    Display() : display(SCREEN_WIDTH, SCREEN_HEIGHT, &Wire, OLED_RESET) {}

    // Initializes both the physical Wire bus and the display hardware
    bool begin() {
        // Automatically start the Teensy hardware Wire bus internally
        Wire.begin();
        Wire.setClock(400000); // 400kHz Fast Mode

        // Initialize the screen peripheral
        if(!display.begin(SSD1306_SWITCHCAPVCC, I2C_ADDRESS)) {
            return false;
        }

        display.clearDisplay();
        display.display();
        return true;
    }

    void clear() {
        display.clearDisplay();
        display.display();
    }

    void showImage(){
        display.clearDisplay();
        display.drawBitmap(0, 0, epd_bitmap_patrick_oled, SCREEN_WIDTH, SCREEN_HEIGHT, SSD1306_WHITE);
        display.display();
    }

  private:
    Adafruit_SSD1306 display;
};

